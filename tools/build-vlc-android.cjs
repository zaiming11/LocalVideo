const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const { spawnSync } = require('node:child_process')
const root = path.resolve(__dirname, '..')
const cache = path.join(__dirname, '.android-build')
const javaHome = process.env.JAVA_HOME || (fs.existsSync('D:/java/bin/javac.exe') ? 'D:/java' : 'C:/Program Files/Common Files/Oracle/Java/javapath/..')
const java = name => path.join(javaHome, 'bin', name + '.exe')
const android = path.join(cache, 'android35.jar')
const vlc = path.join(cache, 'vlc/libvlc-classes.jar')
const support = (require('../native/vlc/dependencies.json').androidSupport || []).map(item => path.join(cache,'vlc',item.classes))
for (const file of [android, vlc, path.join(cache, 'r8.jar'), ...support]) if (!fs.existsSync(file)) throw new Error('Missing native dependency: ' + file + '. Run prepare-vlc.cjs / build-tvbox-android.cjs first.')
const classes = path.join(cache, 'vlc/classes')
fs.mkdirSync(classes, { recursive: true })
const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)])
function run(file, args) { const result = spawnSync(file, args, { stdio: 'inherit' }); if (result.error) throw result.error; if (result.status) process.exit(result.status) }
run(java('javac'), ['-encoding', 'UTF-8', '--release', '8', '-Xlint:-options', '-classpath', android + path.delimiter + vlc, '-d', classes, ...walk(path.join(root, 'native/vlc/src')).filter(file => file.endsWith('.java'))])
const output = path.join(root, 'static/vlc-native/player.jar')
fs.mkdirSync(path.dirname(output), { recursive: true })
run(java('java'), ['-cp', path.join(cache, 'r8.jar'), 'com.android.tools.r8.D8', '--min-api', '23', '--lib', android, '--output', output, ...walk(classes).filter(file => file.endsWith('.class')), vlc, ...support])
const hash = crypto.createHash('sha256').update(fs.readFileSync(output)).digest('hex')
const libs = {}
for (const abi of ['arm64-v8a', 'armeabi-v7a']) libs[abi] = fs.readdirSync(path.join(root, 'static/vlc-native', abi)).filter(file => file.endsWith('.so')).map(name => ({ name, size: fs.statSync(path.join(root, 'static/vlc-native', abi, name)).size }))
fs.writeFileSync(path.join(root, 'core/vlc-native-version.js'), '// Generated by tools/build-vlc-android.cjs\nexport const VLC_NATIVE = ' + JSON.stringify({ hash, version: require('../native/vlc/dependencies.json').android.version, libs }, null, 2) + '\n')
console.log('Android LibVLC component compiled: ' + hash)
